-- 012-metric_types.sql
--
-- Makes "prism"."Metrics" the single source of every metric definition. The UI holds no metric-specific
-- information: the API returns the display fields listed below (never the SQL), and the server builds each
-- chart query from these columns (see docs/OVERVIEW.md §4.3 "Metric types").
--
--   metric_type        percentage | ratio | average | sum   — how Prism builds the calculation:
--                        percentage  ROUND(SUM(num) / NULLIF(SUM(den), 0) * 100, decimals)
--                        ratio       ROUND(SUM(num) / NULLIF(SUM(den), 0), decimals)
--                        average     ROUND(AVG(value), decimals)   (rows with no value are ignored, not zero)
--                        sum         ROUND(SUM(value), decimals)
--   numerator_sql      numerator (percentage, ratio) or value (average, sum): a column expression
--   denominator_sql    denominator (percentage, ratio only)
--   row_condition_sql  optional "only rows where …", applied to every aggregate of the metric (FILTER clause)
--   title, unit, decimal_places, sort_order, is_active — display / listing
--   scale_mode         NULL = the type's default (percentage: 0–100, others: fit to data);
--                      'zero_to_100' | 'fit' | 'fixed' (with scale_min / scale_max)
--
-- Also: a primary key on metric_pk (now generated), a unique metric name, and the legacy
-- valuecolumnsforselectclause / fromclause columns made optional (no longer read).
--
-- Seeds the five metrics the demo fact table supports. Formulas agreed with the owner, Oct 2026.
--
-- RE-RUNNABLE: guarded DDL; existing metric rows are never overwritten (only filled in where still empty).

-- ---- Keys --------------------------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'Metrics_pkey') THEN
    ALTER TABLE "prism"."Metrics" ADD CONSTRAINT "Metrics_pkey" PRIMARY KEY (metric_pk);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_attribute
    WHERE attrelid = '"prism"."Metrics"'::regclass AND attname = 'metric_pk' AND attidentity <> ''
  ) THEN
    ALTER TABLE "prism"."Metrics" ALTER COLUMN metric_pk ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END$$;

-- Move the new identity sequence past the existing keys (008 inserted metric_pk 1 explicitly) before
-- any row is inserted below.
DO $$
DECLARE
  seq TEXT := pg_get_serial_sequence('"prism"."Metrics"', 'metric_pk');
  max_key BIGINT;
  last_key BIGINT;
BEGIN
  SELECT MAX(metric_pk) INTO max_key FROM "prism"."Metrics";
  SELECT last_value INTO last_key FROM pg_sequences WHERE format('%I.%I', schemaname, sequencename) = seq;
  IF max_key IS NOT NULL AND max_key > COALESCE(last_key, 0) THEN
    PERFORM setval(seq, max_key);
  END IF;
END$$;

CREATE UNIQUE INDEX IF NOT EXISTS metrics_name_uk ON "prism"."Metrics" (name);

-- ---- Legacy columns: no longer read, so no longer required -------------------------------------
ALTER TABLE "prism"."Metrics" ALTER COLUMN valuecolumnsforselectclause DROP NOT NULL;
ALTER TABLE "prism"."Metrics" ALTER COLUMN fromclause DROP NOT NULL;

-- ---- New columns ---------------------------------------------------------------------------------
ALTER TABLE "prism"."Metrics" ADD COLUMN IF NOT EXISTS metric_type       TEXT;
ALTER TABLE "prism"."Metrics" ADD COLUMN IF NOT EXISTS numerator_sql     TEXT;
ALTER TABLE "prism"."Metrics" ADD COLUMN IF NOT EXISTS denominator_sql   TEXT;
ALTER TABLE "prism"."Metrics" ADD COLUMN IF NOT EXISTS row_condition_sql TEXT;
ALTER TABLE "prism"."Metrics" ADD COLUMN IF NOT EXISTS title             VARCHAR(60);
ALTER TABLE "prism"."Metrics" ADD COLUMN IF NOT EXISTS unit              VARCHAR(20);
ALTER TABLE "prism"."Metrics" ADD COLUMN IF NOT EXISTS decimal_places    SMALLINT NOT NULL DEFAULT 2;
ALTER TABLE "prism"."Metrics" ADD COLUMN IF NOT EXISTS scale_mode        TEXT;
ALTER TABLE "prism"."Metrics" ADD COLUMN IF NOT EXISTS scale_min         NUMERIC;
ALTER TABLE "prism"."Metrics" ADD COLUMN IF NOT EXISTS scale_max         NUMERIC;
ALTER TABLE "prism"."Metrics" ADD COLUMN IF NOT EXISTS sort_order        INTEGER;
ALTER TABLE "prism"."Metrics" ADD COLUMN IF NOT EXISTS is_active         BOOLEAN NOT NULL DEFAULT TRUE;

-- ---- Seed / complete the five demo metrics -------------------------------------------------------
-- Say/Do Ratio already exists (008): fill in only what is still empty.
UPDATE "prism"."Metrics"
   SET metric_type     = COALESCE(metric_type, 'percentage'),
       numerator_sql   = COALESCE(numerator_sql, 'smf.committed_story_points_completed'),
       denominator_sql = COALESCE(denominator_sql, 'smf.committed_story_points'),
       title           = COALESCE(title, 'Say/Do Ratio'),
       unit            = COALESCE(unit, '%'),
       sort_order      = COALESCE(sort_order, 10)
 WHERE name = 'Say/Do Ratio';

INSERT INTO "prism"."Metrics" (name, metric_type, numerator_sql, denominator_sql, title, unit, scale_mode, sort_order)
SELECT v.name, v.metric_type, v.numerator_sql, v.denominator_sql, v.title, v.unit, v.scale_mode, v.sort_order
  FROM (VALUES
    ('Say/Do Ratio', 'percentage',
     'smf.committed_story_points_completed', 'smf.committed_story_points',
     'Say/Do Ratio', '%', NULL, 10),
    -- Average of the pre-calculated 3-sprint rolling velocity (rows without one are ignored).
    ('Velocity', 'average',
     'smf.avg_velocity_3_sprints', NULL,
     'Velocity (3-sprint average)', 'points', NULL, 20),
    -- Points added or removed, relative to whichever is higher per team-sprint: committed or completed.
    ('Scope Churn', 'percentage',
     'smf.story_points_added_during_sprint + smf.story_points_removed_during_sprint',
     'GREATEST(smf.committed_story_points, smf.story_points_completed)',
     'Scope Churn', '%', NULL, 30),
    -- Typically small percentages, so it starts fitted to the data instead of 0–100.
    ('Estimate Changed', 'percentage',
     'smf.stories_with_modified_estimate', 'smf.total_stories',
     'Estimate Changed', '%', 'fit', 40),
    ('% Estimated', 'percentage',
     'smf.stories_estimated', 'smf.total_stories',
     '% Estimated', '%', NULL, 50)
  ) AS v(name, metric_type, numerator_sql, denominator_sql, title, unit, scale_mode, sort_order)
 WHERE NOT EXISTS (SELECT 1 FROM "prism"."Metrics" m WHERE m.name = v.name);

-- ---- Rules (added after seeding so existing rows are complete) -----------------------------------
ALTER TABLE "prism"."Metrics" ALTER COLUMN metric_type   SET NOT NULL;
ALTER TABLE "prism"."Metrics" ALTER COLUMN numerator_sql SET NOT NULL;
ALTER TABLE "prism"."Metrics" ALTER COLUMN title         SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'metrics_metric_type_ck') THEN
    ALTER TABLE "prism"."Metrics" ADD CONSTRAINT metrics_metric_type_ck
      CHECK (metric_type IN ('percentage', 'ratio', 'average', 'sum'));
  END IF;

  -- percentage and ratio need a denominator; average and sum must not have one.
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'metrics_denominator_ck') THEN
    ALTER TABLE "prism"."Metrics" ADD CONSTRAINT metrics_denominator_ck
      CHECK ((metric_type IN ('percentage', 'ratio')) = (denominator_sql IS NOT NULL));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'metrics_scale_mode_ck') THEN
    ALTER TABLE "prism"."Metrics" ADD CONSTRAINT metrics_scale_mode_ck
      CHECK (scale_mode IS NULL OR scale_mode IN ('zero_to_100', 'fit', 'fixed'));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'metrics_scale_fixed_ck') THEN
    ALTER TABLE "prism"."Metrics" ADD CONSTRAINT metrics_scale_fixed_ck
      CHECK (scale_mode IS DISTINCT FROM 'fixed' OR (scale_min IS NOT NULL OR scale_max IS NOT NULL));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'metrics_decimal_places_ck') THEN
    ALTER TABLE "prism"."Metrics" ADD CONSTRAINT metrics_decimal_places_ck
      CHECK (decimal_places BETWEEN 0 AND 6);
  END IF;
END$$;

COMMENT ON COLUMN "prism"."Metrics".metric_type IS 'percentage | ratio | average | sum: how Prism builds the calculation';
COMMENT ON COLUMN "prism"."Metrics".numerator_sql IS 'Numerator (percentage, ratio) or value (average, sum): a column expression';
COMMENT ON COLUMN "prism"."Metrics".denominator_sql IS 'Denominator (percentage, ratio only): a column expression';
COMMENT ON COLUMN "prism"."Metrics".row_condition_sql IS 'Optional condition applied to every aggregate of the metric';
COMMENT ON COLUMN "prism"."Metrics".scale_mode IS 'NULL = type default; zero_to_100 | fit | fixed (scale_min/scale_max)';
COMMENT ON COLUMN "prism"."Metrics".valuecolumnsforselectclause IS 'Legacy (before SQL/012); not read';
COMMENT ON COLUMN "prism"."Metrics".fromclause IS 'Legacy (before SQL/012); not read';
