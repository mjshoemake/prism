    private static SchemaReview result(List<TableSummary> tables, List<Finding> findings,
                                       List<FocusAreaSuggestion> suggestions, List<String> skipped, Map<String, String> roles) {
        var sorted = new ArrayList<>(findings);
        sorted.sort(Comparator.comparingInt(StarSchemaReviewService::severityRank).thenComparing(Finding::rule));
        long errors = sorted.stream().filter(f -> f.severity().equals(ERROR)).count();
        long warnings = sorted.stream().filter(f -> f.severity().equals(WARNING)).count();
        long notes = sorted.size() - errors - warnings;
        long facts = roles.values().stream().filter("fact"::equals).count();
        long dims = roles.values().stream().filter("dimension"::equals).count();
        var summary = tables.isEmpty() ? "Nothing to review: " + (sorted.isEmpty() ? "" : sorted.get(0).message())
                : "%d tables read (%d fact, %d dimension). %s %d errors, %d warnings, %d notes.".formatted(
                        tables.size(), facts, dims,
                        errors == 0 ? "Prism-compatible as far as the DDL shows." : "Not Prism-compatible yet: fix the errors first.",
                        errors, warnings, notes);
        return new SchemaReview(summary, List.copyOf(tables), List.copyOf(sorted), List.copyOf(suggestions),
                List.copyOf(skipped));
    }

    private static int severityRank(Finding f) {
        return switch (f.severity()) {
            case ERROR -> 0;
            case WARNING -> 1;
            default -> 2;
        };
    }

    private static boolean hasAnyPart(String name, Set<String> words) {
        for (var part : name.toLowerCase(Locale.ROOT).split("_")) {
            if (words.contains(part)) {
                return true;
            }
        }
        return false;
    }

    /** {@code "prism"."Team_Dim"} → {@code team_dim}: the last part, unquoted, lower case (for matching). */
    static String key(String identifier) {
        return unquote(identifier).toLowerCase(Locale.ROOT);
    }

    /** {@code "prism"."Team_Dim"} → {@code Team_Dim}. */
    static String unquote(String identifier) {
        // The last dot-separated part, where dots inside "…" don't separate.
        var text = identifier.strip();
        int start = 0;
        boolean quoted = false;
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            if (c == '"') {
                quoted = !quoted;
            } else if (c == '.' && !quoted) {
                start = i + 1;
            }
        }
        var last = text.substring(start).strip();
        if (last.length() >= 2 && last.startsWith("\"") && last.endsWith("\"")) {
            last = last.substring(1, last.length() - 1).replace("\"\"", "\"");
        }
        return last;
    }

    private static List<String> splitColumns(String parenthesized) {
        var inner = parenthesized.replaceAll("^\\(|\\)$", "");
        var columns = new ArrayList<String>();
        for (var part : inner.split(",")) {
            if (!part.isBlank()) {
                columns.add(key(part));
            }
        }
        return columns;
    }

    private static String firstWords(String statement) {
        var words = statement.strip().split("\\s+", 4);
        return String.join(" ", List.of(words).subList(0, Math.min(3, words.length)));
    }

    private static String tableNameGuess(String statement) {
        var m = Pattern.compile("(?i)CREATE\\s+(?:TEMP\\w*\\s+|UNLOGGED\\s+)?TABLE\\s+(?:IF\\s+NOT\\s+EXISTS\\s+)?([^\\s(]+)")
                .matcher(statement);
        return m.find() ? unquote(m.group(1)) : null;
    }

    private static String title(String tableName) {
        var base = tableName.replaceAll("(?i)(^dim_|_dim$|^d_|_dimension$)", "").replace('_', ' ').strip();
        return base.isEmpty() ? tableName : Character.toUpperCase(base.charAt(0)) + base.substring(1);
    }
